const substitutions=Object.entries(EN).filter(([ar])=>/[؀-ۿ]/.test(ar)&&ar.length>=3).sort((a,b)=>b[0].length-a[0].length);
const arabic=/[\u0600-\u06FF]/;
export function readUI(storage=globalThis.localStorage){
  try{
    const raw=storage?.getItem(UI_STORAGE_KEY);
    const data=raw?JSON.parse(raw):{};
    return {lang:data?.lang==='en'?'en':'ar',theme:data?.theme==='dark'?'dark':'light'};
  }catch{return {...DEFAULT_UI};}
}
export function setUI(prefs,storage=globalThis.localStorage){
  const next={lang:prefs?.lang==='en'?'en':'ar',theme:prefs?.theme==='dark'?'dark':'light'};
  try{storage?.setItem(UI_STORAGE_KEY,JSON.stringify(next));}catch{ /* browser storage disabled: session-only UI */ }
  return next;
}
export function translateText(value,lang='ar'){
  const text=String(value??'');
  if(lang!=='en'||!arabic.test(text))return text;
  const normalized=text.trim();
  if(Object.hasOwn(EN,normalized))return text.replace(normalized,EN[normalized]);
  // Longest Arabic source phrases first; leave numbers, names and technical identifiers untouched.
  let result=text;
  for(const [ar,en] of substitutions)if(result.includes(ar))result=result.replaceAll(ar,en);
  return result;
}
export function translateFragment(root,lang='ar'){
  if(!root||lang!=='en')return root;
  const doc=root.ownerDocument||(typeof document!=='undefined'?document:null);
  if(!doc)return root;
  const NF=doc.defaultView?.NodeFilter||{SHOW_TEXT:4};
  const iterator=doc.createTreeWalker(root,NF.SHOW_TEXT);
  let node;
  while((node=iterator.nextNode())){
    const parent=node.parentElement;
    if(!parent||['SCRIPT','STYLE','TEXTAREA','CODE','PRE'].includes(parent.tagName)
      ||parent.closest('[data-i18n-ignore]')||parent.isContentEditable)continue;
    if(arabic.test(node.nodeValue))node.nodeValue=translateText(node.nodeValue,lang);
  }
  const nodes=[root,...root.querySelectorAll('*')];
  for(const el of nodes)for(const attr of ['placeholder','title','aria-label','alt']){
    if(el.hasAttribute?.(attr)){const val=el.getAttribute(attr);if(arabic.test(val))el.setAttribute(attr,translateText(val,lang));}
  }
  return root;
}
export function applyDocumentUI(prefs,doc=globalThis.document){
  if(!doc?.documentElement)return;
  const {lang,theme}=prefs;
  doc.documentElement.lang=lang;
  doc.documentElement.dir=lang==='ar'?'rtl':'ltr';
  doc.documentElement.dataset.theme=theme;
  doc.documentElement.style.colorScheme=theme;
  doc.title=lang==='ar'?'White tex | إدارة الإنتاج':'White tex | Production Management';
  const themeMeta=doc.querySelector('meta[name="theme-color"]');
  if(themeMeta)themeMeta.setAttribute('content',theme==='dark'?'#0b1220':'#f5f7fa');
}

